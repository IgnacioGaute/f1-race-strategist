// UI dictionaries. `en` is typed as `Messages`, so a missing translation is a
// compile error. Values that come pre-formatted (times, dates, percentages) are
// passed in as strings so formatting stays locale-aware in one place.

type Params = Record<string, string | number | string[]>;

const num = (p: Params | undefined, key: string): number | string => {
  const value = p?.[key];
  return typeof value === "number" || typeof value === "string" ? value : "?";
};
const list = (p: Params | undefined, key: string): string => {
  const value = p?.[key];
  return Array.isArray(value) ? value.join(", ") : String(value ?? "?");
};

